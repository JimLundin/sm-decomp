pub(crate) fn validate(rom: &[u8]) -> Result<(), String> {
    for (at, expected) in slices() {
        // Bank 81 maps directly to file offsets 0x8000..0xffff in this LoROM.
        if rom.get(at..at + expected.len()) != Some(expected) {
            return Err(format!("persistence ROM table differs at {:#08x}", 0x810000 | at));
        }
    }
    Ok(())
}
#[cfg(test)]
pub(crate) fn fixture_rom() -> Vec<u8> {
    let mut rom = vec![0; 0x10000];
    for (at, expected) in slices() {
        rom[at..at + expected.len()].copy_from_slice(expected);
    }
    rom
}
