pub(crate) fn word(bytes: &[u8], at: usize) -> u16 {
    u16::from_le_bytes([bytes[at], bytes[at + 1]])
}
pub(crate) fn set_word(bytes: &mut [u8], at: usize, value: u16) {
    bytes[at..at + 2].copy_from_slice(&value.to_le_bytes());
}
pub(crate) fn rom_index(offset: u16) -> usize {
    0x20000 + usize::from(offset & 0x7fff)
}
pub(crate) fn validate_rom(rom: &[u8]) -> Result<(), String> {
    for (offset, expected) in [(0xe47c, ITEM_SCRIPT), (0xdfaf, SHELL_BURST_SCRIPT)] {
        let start = rom_index(offset);
        let actual = rom
            .get(start..start + expected.len())
            .ok_or_else(|| format!("bank84 script {offset:04x} backing truncated"))?;
        if actual != expected {
            return Err(format!("bank84 script {offset:04x} differs from sealed source"));
        }
    }
    Ok(())
}
