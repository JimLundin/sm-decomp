//! fuzz gen <dir-with-65816-json> [per_opcode]
//!
//! Reads the SingleStepTests / ProcessorTests 65816 JSON files (native mode,
//! `*.n.json`), runs each test's instruction through the *same* emitter the
//! recompiler uses (`recomp::emit::emit_straight`), and writes Rust tests to
//! `out/generated/fuzz.rs`. Then `cargo test -p fuzz` compiles and runs
//! them. A failure means `runtime::ops`/`ea` or the emitter is wrong.
//!
//! Control-flow instructions and block moves are skipped: generated code does
//! not model PC, and those are covered by the frame diff instead.

use std::fmt::Write;
use std::path::PathBuf;

use anyhow::{Context, Result};
use recomp::decode::decode_with;
use recomp::emit::emit_straight;
use serde::Deserialize;

#[derive(Deserialize)]
struct State {
    pc: u32,
    s: u32,
    p: u32,
    a: u32,
    x: u32,
    y: u32,
    dbr: u32,
    d: u32,
    pbr: u32,
    e: u32,
    ram: Vec<(u32, u32)>,
}

#[derive(Deserialize)]
struct Case {
    name: String,
    initial: State,
    #[serde(rename = "final")]
    fin: State,
}

const SKIP: &[&str] = &[
    "JSR", "JSL", "RTS", "RTL", "RTI", "JMP", "JML", "BRA", "BRL", "BPL", "BMI", "BVC", "BVS", "BCC", "BCS", "BNE",
    "BEQ", "BRK", "COP", "WAI", "STP", "WDM", "MVN", "MVP", "XCE", "PLP",
];

fn cpu_lit(s: &State) -> String {
    format!(
        "Cpu {{ a: 0x{:04X}, x: 0x{:04X}, y: 0x{:04X}, s: 0x{:04X}, d: 0x{:04X}, db: 0x{:02X}, pb: 0x{:02X}, p: 0x{:02X}, e: false }}",
        s.a, s.x, s.y, s.s, s.d, s.dbr, s.pbr, s.p
    )
}

fn ram_lit(r: &[(u32, u32)]) -> String {
    let items: Vec<String> = r.iter().map(|(a, v)| format!("(0x{a:06X}, 0x{v:02X})")).collect();
    format!("&[{}]", items.join(", "))
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) != Some("gen") || args.len() < 2 {
        anyhow::bail!("usage: fuzz gen <dir-with-65816-json> [per_opcode=20]");
    }
    let dir = PathBuf::from(&args[1]);
    let per_op: usize = args.get(2).map(|s| s.parse()).transpose()?.unwrap_or(20);

    let mut out = String::from("// Generated by `fuzz gen`. Do not edit.\n");
    let (mut emitted, mut skipped) = (0usize, 0usize);
    let mut files: Vec<_> = std::fs::read_dir(&dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.to_string_lossy().ends_with(".n.json"))
        .collect();
    files.sort();

    for path in files {
        let cases: Vec<Case> =
            serde_json::from_str(&std::fs::read_to_string(&path)?).with_context(|| format!("{}", path.display()))?;
        for (k, c) in cases.iter().take(per_op).enumerate() {
            let i = &c.initial;
            if i.e != 0 || c.fin.e != 0 {
                skipped += 1;
                continue;
            }
            let pc = (i.pbr << 16) | i.pc;
            let read = |a: u32| i.ram.iter().find(|(ra, _)| *ra == a).map(|(_, v)| *v as u8);
            let Some(insn) = decode_with(read, pc, i.p & 0x20 != 0, i.p & 0x10 != 0) else {
                skipped += 1;
                continue;
            };
            if SKIP.contains(&insn.mnem) {
                skipped += 1;
                continue;
            }
            let Ok(code) = emit_straight(&insn) else {
                skipped += 1;
                continue;
            };
            let stem = path.file_name().unwrap().to_string_lossy().replace('.', "_");
            writeln!(
                out,
                "#[test] fn t_{stem}_{k}() {{ // {}\n    let mut mm = support::machine({});\n    let m = &mut mm;\n    m.cpu = {};\n    {code}\n    support::check(m, {}, {}, {:?});\n}}",
                c.name,
                ram_lit(&i.ram),
                cpu_lit(i),
                cpu_lit(&c.fin),
                ram_lit(&c.fin.ram),
                format!("{} {}", c.name, recomp::emit::disasm(&insn)),
            )?;
            emitted += 1;
        }
    }
    std::fs::create_dir_all("out/generated")?;
    std::fs::write("out/generated/fuzz.rs", out)?;
    eprintln!("fuzz: {emitted} cases written, {skipped} skipped → run `cargo test -p fuzz`");
    Ok(())
}
