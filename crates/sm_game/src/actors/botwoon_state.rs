#[derive(Clone, Debug, Default, PartialEq)]
pub struct BotwoonBodyRecord {
    pub projectiles: [u16; 13],
    pub reserved_links: [u16; 3],
    pub visibility: [u16; 13],
    pub reserved_visibility: [u16; 3],
}
impl BotwoonBodyRecord {
    pub(super) fn word(&self, index: usize) -> &u16 {
        match index {
            0..13 => &self.projectiles[index],
            13..16 => &self.reserved_links[index - 13],
            16..29 => &self.visibility[index - 16],
            29..32 => &self.reserved_visibility[index - 29],
            _ => panic!("actor extension index"),
        }
    }
    pub(super) fn word_mut(&mut self, index: usize) -> &mut u16 {
        match index {
            0..13 => &mut self.projectiles[index],
            13..16 => &mut self.reserved_links[index - 13],
            16..29 => &mut self.visibility[index - 16],
            29..32 => &mut self.reserved_visibility[index - 29],
            _ => panic!("actor extension index"),
        }
    }
}
