//! Names for work RAM ($7E:0000-$7F:FFFF) offsets, and the compatibility
//! RAM interface that game modules read and write them through.
//!
//! Extracted from snesrev/sm `variables.h` and `variables_extra.h` (rev 578f90b).
//! c2rust expanded those macros, so the transpiled code reads e.g.
//! `*(g_ram.offset(0x998) as *mut uint16)` where the C said `game_state`.
//! The verifier uses this table to name RAM mismatches. Use these names when
//! replacing raw gameplay accesses (phase 3 of docs/PLAN.md).

/// Byte access to work RAM as the compatibility runtime projects it: owned
/// Session state where it is current, otherwise the RAM bytes themselves.
/// The raw work RAM bytes, without the compatibility projection.
pub trait RawRam {
    fn read_byte(&self, at: usize) -> u8;
    fn write_byte(&self, at: usize, value: u8);
    fn copy_in(&self, at: usize, input: &[u8]);
    fn copy_out(&self, at: usize, out: &mut [u8]);
    fn fill(&self, range: core::ops::Range<usize>, value: u8);
    /// Copy `source` to `destination` as if through a temporary buffer.
    fn copy_within(&self, source: core::ops::Range<usize>, destination: usize);
}

/// The raw work RAM a host owns.
pub trait WorkRamAccess {
    type Ram: RawRam + ?Sized;
    fn ram(&self) -> &Self::Ram;
}

/// Named and raw work RAM together, for modules that need nothing else.
pub trait RamHost: CompatibilityRam + WorkRamAccess {}
impl<T: CompatibilityRam + WorkRamAccess + ?Sized> RamHost for T {}

pub trait CompatibilityRam {
    fn compatibility_byte(&self, at: usize) -> u8;
    fn compatibility_write_byte(&mut self, at: usize, value: u8);
    /// The external observations (joypad keys, frame counter, camera...) as
    /// the host's projection holds them, as a lease's `inputs()`; no lease.
    fn observed_inputs(&self) -> crate::external_inputs::ExternalInputs {
        crate::session_encoding::inputs(&|at| self.compatibility_byte(at))
    }
}

/// `Scalar`: the name is one value at `addr`. `Array`: the name is a pointer
/// to the first element of a table of `ty` starting at `addr`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Shape {
    Scalar,
    Array,
}

#[derive(Clone, Copy, Debug)]
pub struct RamVar {
    pub addr: u32,
    pub name: &'static str,
    /// C type name as written in snesrev (`uint16`, `EnemyData`, ...).
    pub ty: &'static str,
    pub shape: Shape,
}

// One row records address, name, original type and scalar/array shape.
// Each group retains ordered names at base + index * stride.
macro_rules! ram_vars {
    ($($base:literal $(stride $stride:literal)?, $ty:ident $shape:ident => [$($name:tt),+ $(,)?];)*) => {
        /// Sorted by address. Several names can share an address; order is significant.
        pub const RAM_VARS: &[RamVar] = &{
            let mut rows = [RamVar { addr: 0, name: "", ty: "", shape: Shape::Scalar };
                0 $(+ [$(ram_vars!(@name $name)),*].len())*];
            let mut index = 0;
            $(
                let first = index;
                let stride = ram_vars!(@stride $($stride)?);
                $(
                    rows[index] = RamVar {
                        addr: $base + (index - first) as u32 * stride,
                        name: ram_vars!(@name $name),
                        ty: stringify!($ty),
                        shape: Shape::$shape,
                    };
                    index += 1;
                )*
            )*
            assert!(index == rows.len());
            rows
        };

        /// Named scalar word offsets share the verifier's address table.
        pub mod words {
            $(ram_vars!(@offsets word, $base, ram_vars!(@stride $($stride)?), $ty, $shape; $($name),*);)*
        }

        /// Named word-array bases; indices are signed element offsets.
        pub mod word_arrays {
            $(ram_vars!(@offsets array, $base, ram_vars!(@stride $($stride)?), $ty, $shape; $($name),*);)*
        }

        /// Named byte offsets and byte-array bases.
        pub mod bytes {
            $(ram_vars!(@offsets byte, $base, ram_vars!(@stride $($stride)?), $ty, $shape; $($name),*);)*
        }
    };
    (@stride) => { 0 };
    (@stride $stride:literal) => { $stride };
    (@name $name:literal) => { $name };
    (@name $name:ident) => { stringify!($name) };
    (@offsets $kind:ident, $addr:expr, $stride:expr, $ty:ident, $shape:ident;) => {};
    (@offsets $kind:ident, $addr:expr, $stride:expr, $ty:ident, $shape:ident; $name:tt $(, $next:tt)*) => {
        ram_vars!(@$kind $addr, $name, $ty, $shape);
        ram_vars!(@offsets $kind, ($addr) + ($stride), $stride, $ty, $shape; $($next),*);
    };
    (@word $addr:expr, $name:ident, uint16, Scalar) => {
        pub const $name: usize = $addr;
    };
    (@word $addr:expr, $name:ident, uint16, Array) => {};
    (@word $addr:expr, $name:literal, $ty:ident, $shape:ident) => {};
    (@word $addr:expr, $name:ident, uint8, $shape:ident) => {};
    (@array $addr:expr, $name:ident, uint16, Array) => {
        pub const $name: usize = $addr;
    };
    (@array $addr:expr, $name:tt, $ty:ident, $shape:ident) => {};
    (@byte $addr:expr, $name:ident, uint8, $shape:ident) => {
        pub const $name: usize = $addr;
    };
    (@byte $addr:expr, $name:tt, $ty:ident, $shape:ident) => {};
}

