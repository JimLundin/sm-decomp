"""Write sm/src/oracle_patch_policy.rs from tools/snesrev_patches.py.

The oracle reads the generated lists when it installs snesrev's patches; see
the inventory's docstring for the meaning of each field. Run without
arguments to rewrite the Rust lists, or with --check to fail when they are
stale or when the inventory and the Rust patch sites disagree.
"""
import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "sm" / "src" / "oracle_patch_policy.rs"
TABLES = ("CARRY", "BUG_HOOKS", "OTHER_HOOKS", "ROM_PATCHES")
OTHER_HOOK_SITES = {0xA08086, 0x808573}


def inventory():
    sys.path.insert(0, str(ROOT / "tools"))
    import snesrev_patches

    tables = {}
    for table in TABLES:
        entries = getattr(snesrev_patches, table)
        addresses = [entry[0] for entry in entries]
        if len(set(addresses)) != len(addresses):
            raise SystemExit(f"{table} lists an address twice")
        for address, verdict, consequence, faithful, native, routine, reason in entries:
            if (verdict not in ("a", "b", "c") or faithful not in ("removed", "kept", "changed")
                    or native not in ("patched", "follows") or not (consequence and routine and reason)):
                raise SystemExit(f"invalid {table} entry ${address:06X}")
        tables[table] = entries
    return tables


def rust_sites():
    """Patch sites as the Rust oracle installs them."""
    cpu_infra = (ROOT / "sm" / "src" / "cpu_infra.rs").read_text(encoding="utf-8")
    carry = re.search(r"static PATCHED_CARRIES: \[u32; \d+\] = \[(.*?)\];", cpu_infra, re.S).group(1)
    patches = (ROOT / "sm" / "src" / "rom_patches.rs").read_text(encoding="utf-8")
    rom = re.findall(r"\(\s*0x([0-9a-f]{6}),\s*&\[", patches)
    rom += re.findall(r"startup_bytes\(\s*0x([0-9a-f]{6})", patches)
    return {
        "CARRY": {int(value, 16) for value in re.findall(r"0x([0-9a-f]{6})", carry)},
        "BUG_HOOKS": {int(value, 16) for value in re.findall(r"fix_bug_hook\(0x([0-9a-f]{6})", cpu_infra)},
        "OTHER_HOOKS": OTHER_HOOK_SITES,
        "ROM_PATCHES": {int(value, 16) for value in rom},
    }


def declaration(name, values):
    items = ", ".join(f"0x{value:06x}" for value in sorted(values))
    return [f"pub(crate) static {name}: &[u32] = &[{items}];"]


def rustfmt(text):
    """Lay the table out exactly as `cargo fmt` does."""
    result = subprocess.run(["rustfmt", "--edition", "2024"], input=text, cwd=ROOT,
                            capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        raise SystemExit(f"rustfmt failed: {result.stderr.strip()}")
    return result.stdout.replace("\r\n", "\n")


def render(tables):
    lines = [
        "//! Generated by tools/oracle_patch_policy.py from tools/snesrev_patches.py.",
        "//! Do not edit; change the inventory and rerun the script.",
        "#![forbid(unsafe_code)]",
    ]
    for policy, doc, select in (
        ("KEPT", "Kept in both oracle modes: the frame-stepping oracle depends on them.",
         lambda entry: entry[3] == "kept"),
        ("CHANGED", "Always installed, in a variant closer to the original once native follows it.",
         lambda entry: entry[3] == "changed"),
        ("FOLLOWS", "The Rust engine follows the original game here; the default oracle drops them.",
         lambda entry: entry[3] == "removed" and entry[4] == "follows"),
    ):
        for table in TABLES:
            sites = [entry[0] for entry in tables[table] if select(entry)]
            lines.append("")
            lines.append(f"/// {table.replace('_', ' ').lower()}: {doc}")
            lines.extend(declaration(f"{policy}_{table}", sites))
    lines.append("")
    lines.append("/// Every bug-hook site; its byte depends on the policy (see `rom_patches`).")
    lines.extend(declaration("SITES_BUG_HOOKS", [entry[0] for entry in tables["BUG_HOOKS"]]))
    return rustfmt("\n".join(lines) + "\n")


def check_groups(tables):
    """Members of a flip group must exist, share native, and be removable together."""
    import snesrev_patches

    for table, addresses, reason in snesrev_patches.FLIP_GROUPS:
        entries = {entry[0]: entry for entry in tables[table]}
        missing = [f"${address:06X}" for address in addresses if address not in entries]
        if missing:
            raise SystemExit(f"flip group ({reason}) names unknown {table} entries {missing}")
        # Kept and changed entries are both always installed.
        policies = {(entries[address][3] == "removed", entries[address][4]) for address in addresses}
        if len(policies) != 1:
            members = ", ".join(f"${address:06X}={entries[address][3]}/{entries[address][4]}"
                                for address in addresses)
            raise SystemExit(f"flip group ({reason}) must flip together: {members}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the Rust lists are stale")
    args = parser.parse_args()
    tables = inventory()
    for table, sites in rust_sites().items():
        listed = {entry[0] for entry in tables[table]}
        if listed != sites:
            missing = ", ".join(f"${value:06X}" for value in sorted(sites - listed))
            extra = ", ".join(f"${value:06X}" for value in sorted(listed - sites))
            raise SystemExit(f"{table} disagrees with the Rust sites: missing [{missing}], extra [{extra}]")
    check_groups(tables)
    text = render(tables)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/oracle_patch_policy.py")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
