"""Official names for the new crates' game entities, and idiomatic names for
their decompiler-labelled functions.

Data only. `tools/codemod/apply_official_names.py` applies it across the
workspace. Committed data lives in Python or Rust modules, never JSON.

Sources, cited per entry:
- The Super Metroid instruction manual (Nintendo, 1994) and the Super Metroid
  Nintendo Player's Guide (Nintendo, 1994). Wikitroid quotes both under each
  enemy's "Official data" heading, so entries cite that page.
- Patrick Johnston's bank logs, https://patrickjohnston.org/bank/<bank>#f<addr>,
  for routine names and for internal objects that have no official name.
  Bank $A0's enemy header table (https://patrickjohnston.org/bank/A0#fCEBF)
  names every enemy species by header address.

ENTITIES rename words inside identifiers. Each rule gives the current word
sequence and its replacement; the codemod applies the longest match first and
keeps each identifier's case style (snake_case, CamelCase, SCREAMING_CASE).
A file or directory whose stem the rules rename is moved with `git mv`.

PROSE rewrites phrases in the new crates' comments, outside `backticks` and
never in provenance lines ("Was `X`"), which keep the original names on purpose.

FUNCTIONS renames the CamelCase and `sub_XXXXXX` functions to snake_case
names taken from the bank-log heading of the routine at their address. Names
are relative to their module, as in the native code: `baby_metroid_cutscene::
handle_cry`, not `baby_metroid_in_cutscene_handle_cry`.

IDENTIFIERS renames other single identifiers (RAM words, fields) the same way.

LOCALS renames a local variable only inside the named file (`E` -> `e`), where a
workspace-wide rename would also hit unrelated items with the same spelling.

CASE_RULES gives every name a macro declares in a file one case, workspace-wide
(constants.rs's `typed_constants!` labels become SCREAMING_SNAKE_CASE, after
the ENTITIES words are applied).

ALLOW_REMOVALS drops style lints from `#[allow(..)]` attributes once the renames
make them unnecessary.

ALLOW_REASONS gives the style allows that stay a `reason`.

KEPT records names that were checked and deliberately left alone.
"""

