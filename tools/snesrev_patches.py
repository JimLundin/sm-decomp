"""Inventory of the snesrev compatibility patches the oracle applies to the original ROM.

Data only. Committed data lives in Python or Rust modules, never JSON.

The oracle runs the original ROM, but snesrev's port changes it in four ways:

- CARRY: `kPatchedCarrys` in sm/src/cpu_infra.rs. The opcode becomes BRK and
  the oracle runs the original instruction after forcing the carry (C=1 before
  SBC, C=0 before ADC). Hardware uses the actual carry.
- BUG_HOOKS: `patch_bugs_parts` in sm/src/cpu_infra.rs. The opcode becomes BRK
  and the oracle runs a compatibility action (registers, RAM or a new PC)
  before the original instruction. Hardware runs only the original instruction.
- OTHER_HOOKS: hooks inside the instruction dispatch in sm/src/snes/cpu.rs.
- ROM_PATCHES: bytes written by `RomPatches` in sm/src/rom_patches.rs.

The project follows the real game: an oracle difference counts when it is
observable in gameplay (positions, timing, RNG, damage, AI, rendering, audio),
not when it only changes instructions. Each entry is
(address, verdict, consequence, faithful, native, routine, reason):

- verdict "a": gameplay-invisible for every reachable input. It may stay, or be
  adjusted, documented here.
- verdict "b": gameplay-visible; the oracle must follow the real game.
- verdict "c": unknown; it needs a replay against a hardware capture.
- consequence: "none", "visual", "state", "crash", "timing" or "audio".
- faithful: what `SM_ORACLE=faithful` (`tools/verify_dll.py --oracle
  faithful`) does with it. "removed" runs the original code; "kept" leaves the
  patch because the frame-stepping oracle depends on it; "changed" installs a
  variant closer to the original. Faithful mode is for discovery.
- native: "patched" while the Rust engine still reproduces the patched
  behaviour, "follows" once it matches the original game. The default
  `SM_ORACLE=patched` installs every patch whose native is "patched" and none
  marked "follows", so a native fix lands in the same commit that flips its
  entry and the default oracle stays green. When every removable entry
  follows, the default equals faithful mode.

`python tools/oracle_patch_policy.py` writes sm/src/oracle_patch_policy.rs
from these tables; `--check` verifies it is current.

The faithful oracle removes every CARRY site, every BUG_HOOK and the PEA $C2AE
hook, even the invisible ones: none of them is needed to step frames. It keeps
the ROM patches that let the oracle step whole frames without a running beam:
beam spin-wait removals, the main-loop input read, the deferred message box,
the native-audio handshake and the host-owned soft reset. Kept "b" and "c"
entries are open follow-ups that need harness work (input supplied one NMI
earlier, an SPC sound driver, beam timing) and a capture replay.

Routine names and descriptions of the original code come from Patrick
Johnston's bank logs, https://patrickjohnston.org/bank/<bank>#f<address>.
Verdicts are static readings of those logs. Replay evidence so far: the room
E0B5 (Ceres Ridley) capture shows the CARRY sites at $A6:D694/$A6:D698
change Ridley's real-retreat rise, which starts the getaway 4 frames earlier
on hardware, and the faithful oracle's E0B5 to E06B door transition matches
the capture frame for frame.
"""

